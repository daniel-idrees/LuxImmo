package com.example.benchmark

import androidx.benchmark.macro.CompilationMode
import androidx.benchmark.macro.FrameTimingMetric
import androidx.benchmark.macro.StartupMode
import androidx.benchmark.macro.junit4.MacrobenchmarkRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assume.assumeTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Measures scroll performance (frame timing) of the listings list.
 *
 * Scroll jank is the most user-visible performance issue for this list-heavy screen, so this
 * benchmark flings through the `LazyColumn` and reports frame durations (P50/P90/P99) via
 * [FrameTimingMetric]. Watch the high percentiles — those are the dropped frames users feel.
 *
 * The two test methods run the *same* flow under different [CompilationMode]s so you can
 * confirm the baseline profile (generated by [BaselineProfileGenerator]) actually improves
 * frame timing:
 *  - [scrollNoCompilation] — JIT only, the worst case.
 *  - [scrollBaselineProfile] — uses the bundled baseline profile (what most users get).
 *
 * Run against a release/benchmark build on a physical device for representative numbers.
 */
@RunWith(AndroidJUnit4::class)
class ListingsScrollBenchmark {
    @get:Rule
    val benchmarkRule = MacrobenchmarkRule()

    @Test
    fun scrollNoCompilation() = scroll(CompilationMode.None())

    @Test
    fun scrollBaselineProfile() = scroll(CompilationMode.Partial())

    private fun scroll(compilationMode: CompilationMode) = benchmarkRule.measureRepeated(
        packageName = PACKAGE_NAME,
        metrics = listOf(FrameTimingMetric()),
        compilationMode = compilationMode,
        // WARM keeps the process but recreates the activity, isolating scroll cost from
        // cold-start cost (which StartupBenchmark already covers).
        startupMode = StartupMode.WARM,
        iterations = 10,
        setupBlock = {
            pressHome()
            startActivityAndWait()
        },
    ) {
        // If the list never loads (e.g. offline emulator), skip rather than report a bogus
        // zero-frame measurement.
        assumeTrue("Listings list did not load; skipping scroll measurement.", scrollListings())
    }
}
